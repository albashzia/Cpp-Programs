#include <iostream>
using namespace std;
int main() {
    int a, b;
    cout << "Enter first number: ";
    cin >> a;
    cout << "Enter second number: ";
    cin >> b;
    cout << "Sum of "<<a<<" and "<<b<<" is "<<a + b;
    cout << endl;
    cout<<"Difference of "<<a<<" and "<<b<<" is "<<a - b;
    cout << endl;
    cout<<"Product of "<<a<<" and "<<b<<" is "<<a * b;
    cout << endl;
    cout<<"Quotient of "<<a<<" is "<<b/a;
}